import assert from 'node:assert/strict';
import { readdir } from 'node:fs/promises';
import * as api from '../dist/index.js';
import { families } from './component-catalogue.mjs';
import { aiFingerprint, readText } from './ai-freshness.mjs';
const contract = JSON.parse(await readText('ai/contract.json'));
const pkg = JSON.parse(await readText('package.json'));
assert.equal(contract.package, pkg.name, 'AI contract package name is stale: run npm run build');
assert.equal(contract.version, pkg.version, 'AI contract package version is stale: run npm run build');
const files = (await readdir('dist')).filter(f => f.endsWith('.d.ts')).sort();
const declarations = Object.fromEntries(await Promise.all(files.map(async f => [f, await readText(`dist/${f}`)])));
// Serein design tokens (colour, type, spacing, motion) followed by this package's theme layer.
const tokens = `${await readText('node_modules/@serein-ui/tokens/dist/css/tokens.css')}\n${await readText('src/tokens.css')}`;
const guide = await readText('ai/README.md');
const composition = await readText('ai/COMPOSITION.md');
const workflowSources = ['Invoices.tsx', 'Settings.tsx', 'Onboarding.tsx', 'Shell.tsx', 'model.ts', 'workflows.css'];
const exampleFiles = [...workflowSources, 'README.md'];
const examples = Object.fromEntries(await Promise.all(exampleFiles.map(async name => [name, await readText(`ai/examples/${name}`)])));
assert.deepEqual((await readdir('ai/examples')).sort(), exampleFiles.sort(), 'AI examples must contain only the explicit generated mirror set');
assert.equal(contract.fingerprint, aiFingerprint({ declarations, tokens, guide, composition, examples }), 'AI contract is stale: run npm run build');
assert.deepEqual([...contract.components, ...contract.hooks].sort(), Object.keys(api).sort(), 'AI index must cover exactly the public runtime exports');
assert.deepEqual(contract.families, families, 'AI component families are stale');
const text = await readText('ai/llms-full.txt');
for (const declaration of Object.values(declarations)) assert.ok(text.includes(declaration), 'Missing API declaration in full text');
assert.ok(text.includes(tokens), 'Missing tokens');
assert.ok(text.includes(composition), 'Missing composition guidance');
for (const [name, example] of Object.entries(examples)) assert.ok(text.includes(example), `Missing workflow example in full text: ${name}`);
assert.equal(await readText('docs/agent-api.generated.md'), text, 'Storybook API mirror is stale');
assert.equal(await readText('docs/ai-integration.generated.md'), guide, 'Storybook integration mirror is stale');
assert.equal(await readText('docs/composition.generated.md'), composition, 'Storybook composition mirror is stale');
console.log(`AI contract verified: ${contract.components.length} components, ${contract.hooks.length} hook, current declarations, tokens, and ${workflowSources.length} workflow mirrors.`);
